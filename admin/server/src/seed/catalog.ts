function makeVariants(
  productIndex: number,
  price: number,
  specs: Array<{ size: string; color: string; stock: number; rented?: number }>,
  options?: { rental?: boolean; threshold?: number },
): Variant[] {
  return specs.map((spec, i) => {
    const sizeCode = spec.size
      .toUpperCase()
      .replace(/[^A-Z0-9]+/g, "")
      .slice(0, 3);
    const colorCode = colorCodes[spec.color] ?? spec.color.slice(0, 3).toUpperCase();
    return {
      id: `var_${String(productIndex).padStart(3, "0")}_${i + 1}`,
      sku: `FC-${String(productIndex).padStart(3, "0")}-${sizeCode}-${colorCode}`,
      size: spec.size,
      color: spec.color,
      price,
      rentalPrice: options?.rental === false ? 0 : Math.max(2, Math.round(price * 0.12)),
      stock: spec.stock,
      rented: spec.rented ?? 0,
      lowStockThreshold: options?.threshold ?? 6,
      rentWindowDays: 5,
    };
  });
}

